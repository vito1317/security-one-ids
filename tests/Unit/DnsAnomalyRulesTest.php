    /** A real answer that resolved, for the rules that need an address. */
    private const ANSWER_GITHUB_RESOLVED = '{"timestamp":"2026-08-28T23:05:29.813420+0800","flow_id":371385289636133,"event_type":"dns","src_ip":"192.168.1.114","src_port":43489,"dest_ip":"8.8.8.8","dest_port":53,"proto":"UDP","pkt_src":"wire/pcap","dns":{"version":2,"type":"answer","id":858,"flags":"8180","qr":true,"rd":true,"ra":true,"opcode":0,"rrname":"api.github.com","rrtype":"A","rcode":"NOERROR","answers":[{"rrname":"api.github.com","rrtype":"A","ttl":23,"rdata":"20.27.177.116"}],"grouped":{"A":["20.27.177.116"]}}}';

    private const LIVE_LOG = '/var/log/suricata/eve.json';

    /** A fixed instant inside the measured corpus, so nothing depends on now(). */
    private const T0 = 1787929529.0;

    private DnsEventNormalizer $normalizer;
    private DnsAnomalyRules $rules;

    /** Kept so a test can assert what the rules had to work with, not just what they said. */
    private DnsResolutionWindow $window;

    protected function setUp(): void
    {
        parent::setUp();

        $this->normalizer = new DnsEventNormalizer();
        $this->window = new DnsResolutionWindow();
        $this->rules = new DnsAnomalyRules($this->window);
    }

    /* ------------------------------------------------------------------ */
    /* The negative direction, on real traffic                             */
    /* ------------------------------------------------------------------ */

    /**
     * Replayed over this host's live DNS log: not one finding.
     *
     * The same pass re-measures the two facts the thresholds were set from, so
     * the margin is asserted rather than remembered: no parent domain reaches
     * more than a couple of distinct NXDOMAIN names in a window, and neither
     * does the host as a whole.
     *
     * Skipped rather than failed when the log cannot supply 20,000 rows,
     * because "we could not look" is a different result from "there was nothing
     * there", and the skip message says which one happened.
     */
    public function test_it_is_silent_on_twenty_thousand_real_dns_events(): void
    {
        $lines = $this->liveDnsLines();

        if (count($lines) < 20000) {
            $this->markTestSkipped(
                'not enough live DNS telemetry to judge silence: ' . count($lines)
                . ' rows in the tail of ' . self::LIVE_LOG . ', 20000 required'
            );
        }

        $window = new DnsResolutionWindow();
        $rules = new DnsAnomalyRules($window);

        $answers = 0;
        $nxdomain = 0;
        $findings = [];
        $maxPerParent = 0;
        $maxHostWide = 0;

        foreach ($lines as $line) {
            $event = $this->normalizer->normalizeLine($line);

            if ($event === null) {
                continue;
            }

            foreach ($rules->evaluate($event) as $finding) {
                $findings[] = $finding['rule'] . ' ' . $finding['reason'];
            }

            if (($event['dns']['type'] ?? '') !== 'answer') {
                continue;
            }

            $answers++;

            if (($event['dns']['rcode'] ?? '') !== 'NXDOMAIN') {
                continue;
            }

            $nxdomain++;
            $parent = $rules->parentDomain($event['dns']['rrname']);
            $maxPerParent = max($maxPerParent, count($window->distinctNxdomainNames($parent)));
            $maxHostWide = max($maxHostWide, count($window->distinctNxdomainHostWide()['names']));
        }

        // Reported in the failure message rather than kept quiet, so a
        // regression says how much traffic it took to produce and which rule
        // it was.
        $this->assertSame(
            [],
            $findings,
            sprintf(
                'false positives over %d real rows (%d answers, %d NXDOMAIN): %s',
                count($lines),
                $answers,
                $nxdomain,
                implode(' | ', array_slice($findings, 0, 5))
            )
        );

        $this->assertGreaterThan(5000, $answers, 'the replay has to contain answers to have judged anything');
        $this->assertGreaterThan(0, $nxdomain, 'and NXDOMAIN answers, or the primary rule was never exercised');

        // The measurement the DNS-001 threshold of 12 was set from. Measured at
        // the time of writing: 1, at every window length from 60s to 900s.
        $this->assertLessThan(
            12,
            $maxPerParent,
            "a real parent domain reached {$maxPerParent} distinct NXDOMAIN names in a 300s window"
        );

        // And the DNS-002 threshold of 18. Measured: 3 in a 300s window.
        $this->assertLessThan(
            18,
            $maxHostWide,
            "real traffic reached {$maxHostWide} distinct NXDOMAIN names host wide in a 300s window"
        );

        $this->assertSame([], $this->normalizer->rejections(), 'real rows must not be rejected');
    }

    /**
     * Why entropy is not the trigger, asserted against the live log.
     *
     * This host's own traffic contains a name whose leftmost label clears the
     * entropy floor these rules use for corroboration, so an entropy trigger
     * would have fired on real traffic; nothing in the corpus meets the
     * conjunction DNS-004 actually uses.
     */
    public function test_entropy_alone_would_fire_on_real_traffic_and_the_conjunction_does_not(): void
    {
        $lines = $this->liveDnsLines();

        if ($lines === []) {
            $this->markTestSkipped('no live DNS telemetry to measure entropy against');
        }

        $names = [];

        foreach ($lines as $line) {
            $event = $this->normalizer->normalizeLine($line);

            if ($event !== null) {
                $names[$event['dns']['rrname']] = true;
            }
        }

        $entropyHits = [];
        $conjunctionHits = [];

        foreach (array_keys($names) as $name) {
            $features = $this->rules->domainFeatures((string) $name);

            if ($features['entropy'] >= 3.0) {
                $entropyHits[] = $name;
            }

            if ($features['entropy'] >= 3.0
                && $features['digit_ratio'] >= 0.2
                && $features['label_length'] >= 12
            ) {
                $conjunctionHits[] = $name;
            }
        }

        $this->assertNotSame(
            [],
            $entropyHits,
            'if no real name clears 3.0 bits then this host cannot demonstrate the problem any more'
        );

        $this->assertSame(
            [],
            $conjunctionHits,
            'the conjunction must be clean on real names: ' . implode(', ', $conjunctionHits)
        );
    }

    /**
     * The single loudest real name, on its own.
     *
     * 3.88 bits over 22 characters with digits in it, refused by the resolver
     * eight times, and generated by this repository's own test suite. It must
     * produce nothing: one name repeated is one distinct name.
     */
    public function test_our_own_test_suites_probe_is_silent(): void
    {
        $findings = [];

        for ($i = 0; $i < 8; $i++) {
            $event = $this->real(self::ANSWER_OWN_TEST_PROBE, self::T0 + ($i * 30));
            $findings = array_merge($findings, $this->rules->evaluate($event));
        }

        $this->assertSame([], $findings);

        // And the reason it is silent is the count, not the shape: this name is
        // above every corroborating threshold in the file.
        $features = $this->rules->domainFeatures('no-such-host-abc123xyz.invalid');
        $this->assertGreaterThan(3.5, $features['entropy']);
        $this->assertGreaterThan(0.1, $features['digit_ratio']);
        $this->assertGreaterThan(20, $features['label_length']);
    }

    /**
     * The repeated NXDOMAIN set this host really produces, at the worst share
     * ever measured on it.
     *
     * 181 refusals of one Docker hostname and 64 of one container service name
     * is 96% of the NXDOMAIN in the corpus. Here they are replayed as 8.3% of a
     * stream of answers, which is above the worst 300-second window measured on
     * real traffic (8.0% at a denominator of 50 or more, against a baseline of
     * 2.19%), and nothing fires: a rate rule reads this as constant failure, a
     * distinct-count rule reads it as two names.
     */
    public function test_the_hosts_own_repeated_nxdomain_set_is_silent(): void
    {
        $findings = [];
        $nxdomain = 0;

        for ($i = 0; $i < 3060; $i++) {
            // One in twelve, which is 8.3%, alternating the two names this host
            // really fails to resolve.
            if ($i % 12 === 0) {
                $line = $nxdomain % 3 === 0
                    ? self::ANSWER_NGINX_PROXY_NXDOMAIN
                    : self::ANSWER_DOCKER_NXDOMAIN;
                $nxdomain++;
                $event = $this->real($line, self::T0 + ($i * 0.25));
            } else {
                $event = $this->resolved('api.github.com', self::T0 + ($i * 0.25), '20.27.177.116');
            }

            $findings = array_merge($findings, $this->rules->evaluate($event));
        }

        $this->assertSame([], $findings);
        $this->assertSame(255, $nxdomain, 'the corpus NXDOMAIN volume, all of it in two names');
        $this->assertSame(2, $this->rules->basis()['distinct_nxdomain']);
    }

    /**
     * What the same two names do when literally nothing else resolves.
     *
     * Not a shape this host produces (measured, the worst 300-second window is
     * 8.0% NXDOMAIN), but worth pinning down because it is the boundary between
     * the two kinds of rule in this file. The counting rules stay silent, since
     * two names repeated a hundred times is still two names, and only the rate
     * rule speaks, which is exactly what it is for: a resolver answering
     * nothing but NXDOMAIN is broken, or the destination has been sinkholed.
     * It is graded low because it cannot tell those two apart.
     */
    public function test_a_pure_nxdomain_stream_is_a_rate_finding_and_not_a_dga_finding(): void
    {
        $findings = [];

        for ($i = 0; $i < 120; $i++) {
            $line = $i % 3 === 0 ? self::ANSWER_NGINX_PROXY_NXDOMAIN : self::ANSWER_DOCKER_NXDOMAIN;
            $findings = array_merge($findings, $this->rules->evaluate($this->real($line, self::T0 + ($i * 1.5))));
        }

        $this->assertSame(['DNS-003'], array_column($findings, 'rule'));
        $this->assertStringContainsString('100%', $findings[0]['reason']);
        $this->assertStringContainsString('over 2 distinct names', $findings[0]['reason']);
    }

    /* ------------------------------------------------------------------ */
    /* The positive direction                                              */
    /* ------------------------------------------------------------------ */

    /**
     * A synthetic DGA burst: 30 distinct 12-character labels under one parent,
     * every one NXDOMAIN, 1.7 seconds apart.
     *
     * Three things are asserted, not one. It fires; it fires on the twelfth
     * name rather than the thirtieth, so the threshold is where the docblock
     * says it is; and it fires ONCE, because the governor cannot deduplicate
     * DNS findings (its signature is built from username, binary and command
     * line, all empty here) and nineteen copies of one burst is how a rule gets
     * switched off.
     */
    public function test_it_fires_once_on_a_synthetic_dga_burst_under_one_parent(): void
    {
        $fired = [];

        foreach ($this->dgaLabels(30, 12, 4242) as $index => $label) {
            foreach ($this->rules->evaluate(
                $this->real(self::ANSWER_DOCKER_NXDOMAIN, self::T0 + ($index * 1.7), $label . '.dga-example.com')
            ) as $finding) {
                $fired[] = ['index' => $index, 'finding' => $finding];
            }
        }

        $this->assertCount(1, $fired, 'one burst is one finding');
        $this->assertSame(11, $fired[0]['index'], 'the twelfth distinct name is the threshold');

        $finding = $fired[0]['finding'];
        $this->assertSame('DNS-001', $finding['rule']);
        $this->assertSame('critical', $finding['severity'], 'generated labels corroborate the count');
        $this->assertSame('T1568.002', $finding['mitre']);
        $this->assertStringContainsString('12 distinct names under dga-example.com', $finding['reason']);
        $this->assertStringContainsString('NXDOMAIN', $finding['reason']);
    }

    /**
     * A burst under one parent is one finding on a real host too, not two.
     *
     * The burst test above is clean: one parent, nothing else in the window. A
     * real host is not. This one's everyday NXDOMAIN traffic is two names —
     * a Docker hostname and the container service name `nginx-proxy`, together
     * 96% of the corpus NXDOMAIN — under two different parents, because a
     * single-label name is its own parent. So a burst under one parent arrived
     * with two of DNS-002's three required parents already in the window, and
     * DNS-002 fired alongside DNS-001 saying the same thing less specifically.
     *
     * That matters beyond tidiness. A responder who sees two rules agree reads
     * it as two pieces of evidence, and the second one names no parent, so it
     * is the less actionable of the two. The conditions are now disjoint: if
     * any parent holds enough names for the per-parent rule, that rule owns the
     * window.
     */
    public function test_a_single_parent_burst_beside_real_background_fires_only_the_per_parent_rule(): void
    {
        $fired = [];

        // The background this host really produces, repeated the way it really
        // is: two names, two parents, many answers.
        for ($i = 0; $i < 20; $i++) {
            $line = $i % 2 === 0 ? self::ANSWER_DOCKER_NXDOMAIN : self::ANSWER_NGINX_PROXY_NXDOMAIN;

            foreach ($this->rules->evaluate($this->real($line, self::T0 + $i * 0.4)) as $finding) {
                $fired[] = $finding;
            }
        }

        $this->assertSame([], $fired, 'the background alone is not a finding');

        foreach ($this->dgaLabels(24, 12, 90210) as $index => $label) {
            foreach ($this->rules->evaluate(
                $this->real(self::ANSWER_DOCKER_NXDOMAIN, self::T0 + 10.0 + ($index * 1.7), $label . '.dga-example.com')
            ) as $finding) {
                $fired[] = $finding;
            }
        }

        $rules = array_map(static fn (array $f): string => $f['rule'], $fired);

        $this->assertSame(['DNS-001'], $rules, 'one burst, one rule, and it is the one that names the parent');

        // The host-wide count really was over its own threshold, so the rule
        // stayed quiet by the disjointness condition rather than for want of
        // material: 24 generated names plus the two background ones.
        $spread = $this->window->distinctNxdomainHostWide();
        $this->assertGreaterThanOrEqual(18, count($spread['names']));
        $this->assertGreaterThanOrEqual(3, count($spread['parents']));
        $this->assertGreaterThanOrEqual(12, $spread['largest_parent']);
    }

    /**
     * The same burst spread across parent domains.
     *
     * 24 names over 4 parents, 6 each, so no parent reaches the DNS-001
     * threshold. This is a DGA that walks TLDs, and the per-parent count cannot
     * see it.
     */
    public function test_a_burst_spread_across_parents_fires_the_host_wide_rule(): void
    {
        $fired = [];
        $index = 0;

        foreach (['a-example.com', 'b-example.net', 'c-example.org', 'd-example.info'] as $parent) {
            foreach ($this->dgaLabels(6, 12, 11 + $index) as $label) {
                foreach ($this->rules->evaluate(
                    $this->real(self::ANSWER_DOCKER_NXDOMAIN, self::T0 + ($index * 2.0), $label . '.' . $parent)
                ) as $finding) {
                    $fired[] = ['index' => $index, 'finding' => $finding];
                }

                $index++;
            }
        }

        $this->assertCount(1, $fired);
        $this->assertSame('DNS-002', $fired[0]['finding']['rule']);
        $this->assertSame('high', $fired[0]['finding']['severity']);
        $this->assertSame(17, $fired[0]['index'], 'the eighteenth distinct name is the threshold');

        // Three parents, not four: the eighteenth name arrives while the fourth
        // parent has not been queried yet, which is the rule firing as early as
        // its own conditions allow rather than waiting for a rounder number.
        $this->assertStringContainsString('3 different parent domains', $fired[0]['finding']['reason']);
    }

    /**
     * Single-label generated names, which have no parent to group under.
     *
     * Every name is its own parent, so DNS-001 can never see them. It is not a
     * hypothetical shape: this host really does resolve single-label names
     * (`nginx-proxy`, 64 refusals), which is why the normaliser flags them
     * instead of dropping them.
     */
    public function test_single_label_generated_names_are_caught_host_wide(): void
    {
        $fired = [];

        foreach ($this->dgaLabels(20, 12, 12) as $index => $label) {
            foreach ($this->rules->evaluate(
                $this->real(self::ANSWER_NGINX_PROXY_NXDOMAIN, self::T0 + ($index * 2.0), $label)
            ) as $finding) {
                $fired[] = $finding;
            }
        }

        $this->assertCount(1, $fired);
        $this->assertSame('DNS-002', $fired[0]['rule']);
    }

    /**
     * An alphabetic-only DGA, which is Conficker's shape.
     *
     * It must still fire, because the trigger is the count and the count does
     * not care what alphabet the names use. And it must NOT be escalated to
     * critical: with no digits and a lower mean entropy there is nothing to
     * corroborate with, and search-domain expansion or a broken client is also
     * consistent with what was seen. Saying so in the finding is the point.
     */
    public function test_an_alphabetic_only_dga_fires_but_is_not_escalated(): void
    {
        $fired = [];

        foreach ($this->dgaLabels(30, 10, 7, 'abcdefghijklmnopqrstuvwxyz') as $index => $label) {
            foreach ($this->rules->evaluate(
                $this->real(self::ANSWER_DOCKER_NXDOMAIN, self::T0 + ($index * 1.5), $label . '.ws-example.net')
            ) as $finding) {
                $fired[] = $finding;
            }
        }

        $this->assertCount(1, $fired);
        $this->assertSame('DNS-001', $fired[0]['rule']);
        $this->assertSame('high', $fired[0]['severity']);
        $this->assertStringContainsString('0% of them contain digits', $fired[0]['reason']);
        $this->assertStringContainsString('not obviously generated', $fired[0]['reason']);
    }

    /**
     * A generated name that actually resolved: the rendezvous.
     *
     * Reported once per name per window, for the same reason as the burst: a
     * name is re-resolved every time its TTL expires (measured on this host,
     * the median answer TTL is 144 seconds), so without the cooldown one C2
     * domain would produce a finding every couple of minutes forever.
     */
    public function test_a_generated_name_that_resolved_is_reported_once(): void
    {
        $first = $this->rules->evaluate($this->resolved('a7f3k92m1x8q.rendezvous-example.com', self::T0));
        $again = $this->rules->evaluate($this->resolved('a7f3k92m1x8q.rendezvous-example.com', self::T0 + 150));

        $this->assertCount(1, $first);
        $this->assertSame('DNS-004', $first[0]['rule']);
        $this->assertSame('medium', $first[0]['severity']);
        $this->assertStringContainsString('185.199.108.153', $first[0]['reason']);
        $this->assertSame([], $again, 'the same name inside the window is the same fact');

        // The name that failed is DNS-001's business, not this rule's: an
        // answer with no address is not a host about to connect anywhere.
        $rules = new DnsAnomalyRules(new DnsResolutionWindow());
        $this->assertSame([], $rules->evaluate(
            $this->real(self::ANSWER_DOCKER_NXDOMAIN, self::T0, 'a7f3k92m1x8q.rendezvous-example.com')
        ));
    }

    /* ------------------------------------------------------------------ */
    /* Refusing to judge, and the window                                   */
    /* ------------------------------------------------------------------ */

    /**
     * The rate rule has no answer without a denominator, and says so.
     *
     * Twenty answers of which nineteen are NXDOMAIN is 95%, which is far above
     * every threshold in the file, and it is still not a judgement: the
     * measured minimum number of answers in a trailing 300-second window on
     * this host is 1, where a single refused Docker hostname reads as 100%.
     * The refusal is counted so that a quiet result cannot be mistaken for a
     * clean one.
     */
    public function test_the_rate_rule_refuses_to_judge_without_a_denominator(): void
    {
        for ($i = 0; $i < 19; $i++) {
            $this->assertSame([], $this->rules->evaluate(
                $this->real(self::ANSWER_DOCKER_NXDOMAIN, self::T0 + $i)
            ));
        }

        $this->assertSame([], $this->rules->evaluate($this->resolved('api.github.com', self::T0 + 20)));

        $basis = $this->rules->basis();

        $this->assertFalse($basis['rate_basis'], 'twenty answers is not a denominator');
        $this->assertSame(20, $basis['answers']);
        $this->assertSame(20, $basis['withheld']['DNS-003'], 'every withheld judgement is counted');
        $this->assertSame($this->rules->withheld(), $basis['withheld']);
    }

    /**
     * With a denominator, repeated failure of a small set is reported low.
     *
     * This is the shape the distinct-count rules deliberately cannot see: one
     * name failing over and over, which is a sinkholed destination or a broken
     * resolver rather than a generation algorithm. Graded low because it cannot
     * tell those apart.
     */
    public function test_the_rate_rule_fires_on_a_small_set_failing_repeatedly(): void
    {
        $fired = [];

        for ($i = 0; $i < 100; $i++) {
            $event = $i % 2 === 0
                ? $this->real(self::ANSWER_DOCKER_NXDOMAIN, self::T0 + ($i * 2.0), 'sinkholed.example.com')
                : $this->resolved('api.github.com', self::T0 + ($i * 2.0));

            foreach ($this->rules->evaluate($event) as $finding) {
                $fired[] = ['index' => $i, 'finding' => $finding];
            }
        }

        $this->assertCount(1, $fired);
        $this->assertSame('DNS-003', $fired[0]['finding']['rule']);
        $this->assertSame('low', $fired[0]['finding']['severity']);
        $this->assertSame(49, $fired[0]['index'], 'it waits for the fiftieth answer, then divides');
        $this->assertStringContainsString('1 distinct', $fired[0]['finding']['reason']);
        $this->assertSame(1, $this->rules->basis()['distinct_nxdomain']);
    }

    /**
     * The window has to be carried across the collection cycle, and this is
     * what happens when it is not.
     *
     * Measured on this host, `ids:sync-edr` runs in a fresh PHP process every
     * 30 seconds (security-one-watchdog.sh, EDR_INTERVAL=30). A burst of 30
     * names arriving three per cycle therefore never reaches a threshold inside
     * one process, and the rule silently cannot fire, which is the exact
     * failure mode NET-003 was fixed for. Exporting and restoring the window
     * makes the same traffic alert in the fourth cycle.
     */
    public function test_a_burst_thinner_than_one_cycle_needs_the_window_carried(): void
    {
        $labels = $this->dgaLabels(30, 12, 21);

        $withoutCarrying = $this->replayInCycles($labels, false);
        $withCarrying = $this->replayInCycles($labels, true);

        $this->assertSame([], $withoutCarrying, 'three names per 30s process cannot reach 12 in one process');
        $this->assertCount(1, $withCarrying);
        $this->assertSame('DNS-001', $withCarrying[0]['rule']);
    }

    /** The window is small enough to persist, measured rather than assumed. */
    public function test_the_window_state_is_small_enough_to_carry(): void
    {
        foreach ($this->dgaLabels(30, 12, 3) as $index => $label) {
            $this->rules->evaluate(
                $this->real(self::ANSWER_DOCKER_NXDOMAIN, self::T0 + ($index * 2.0), $label . '.dga-example.com')
            );
        }

        $state = $this->rules->window()->export();
        $encoded = json_encode($state);

        $this->assertIsString($encoded);
        $this->assertLessThan(16384, strlen($encoded), 'a window that cannot be persisted cheaply will not be');

        // Restoring must reproduce the counts, or carrying it across a cycle
        // would quietly lose the burst it exists to remember.
        $restored = new DnsResolutionWindow();
        $restored->restore(json_decode($encoded, true));

        $this->assertSame(
            count($this->rules->window()->distinctNxdomainHostWide()['names']),
            count($restored->distinctNxdomainHostWide()['names'])
        );
        $this->assertSame($this->rules->window()->answerCounts(), $restored->answerCounts());

        // And the cooldown must survive with it, or the first event of the next
        // cycle re-reports the burst the previous cycle already reported.
        $this->assertFalse($restored->markFired('DNS-001:dga-example.com', $this->rules->window()->clock(), 300));
    }

