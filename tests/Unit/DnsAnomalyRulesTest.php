/**
 * The DGA rules, proved in both directions.
 *
 * Both directions, because either one alone is worthless. A detector that has
 * only been shown to fire might fire on everything, and a detector that has
 * only been shown to be quiet might be incapable of firing at all, which is the
 * worse failure: the coverage still appears on the rule list.
 *
 * The negative direction is replayed over this host's real DNS traffic from
 * /var/log/suricata/eve.json rather than over invented "clean" events, because
 * invented traffic agrees with whatever the rule already assumes. It caught the
 * fact that the highest-entropy name in this host's entire DNS history is
 * generated by this project's own test suite.
 *
 * Every synthetic event below is a real log line with one or two members
 * replaced, so everything the rules read except the name and the clock is real.
 */
class DnsAnomalyRulesTest extends TestCase
{
    /** A real NXDOMAIN answer. 181 of the 255 NXDOMAIN answers in the corpus. */
    private const ANSWER_DOCKER_NXDOMAIN = '{"timestamp":"2026-08-28T23:05:33.655885+0800","flow_id":1644109239592472,"event_type":"dns","src_ip":"192.168.1.114","src_port":34204,"dest_ip":"8.8.8.8","dest_port":53,"proto":"UDP","pkt_src":"wire/pcap","dns":{"version":2,"type":"answer","id":38508,"flags":"8183","qr":true,"rd":true,"ra":true,"opcode":0,"rrname":"host.docker.internal","rrtype":"A","rcode":"NXDOMAIN","authorities":[{"rrname":"","rrtype":"SOA","ttl":86399,"soa":{"mname":"a.root-servers.net","rname":"nstld.verisign-grs.com","serial":2026082800,"refresh":1800,"retry":900,"expire":604800,"minimum":86400}}]}}';

    /** A real single-label NXDOMAIN: a Docker service name, 64 answers. */
    private const ANSWER_NGINX_PROXY_NXDOMAIN = '{"timestamp":"2026-08-28T23:06:15.411747+0800","flow_id":2020778053971253,"event_type":"dns","src_ip":"192.168.1.114","src_port":36505,"dest_ip":"8.8.8.8","dest_port":53,"proto":"UDP","pkt_src":"wire/pcap","dns":{"version":2,"type":"answer","id":32507,"flags":"8183","qr":true,"rd":true,"ra":true,"opcode":0,"rrname":"nginx-proxy","rrtype":"A","rcode":"NXDOMAIN","authorities":[{"rrname":"","rrtype":"SOA","ttl":86380,"soa":{"mname":"a.root-servers.net","rname":"nstld.verisign-grs.com","serial":2026082800,"refresh":1800,"retry":900,"expire":604800,"minimum":86400}}]}}';

    /**
     * The highest leftmost-label entropy in this host's whole DNS history:
     * 3.88 bits over 22 characters, with digits in it, and NXDOMAIN. It is
     * ours. tests/Unit/NetworkContainmentTest.php asks the containment code to
