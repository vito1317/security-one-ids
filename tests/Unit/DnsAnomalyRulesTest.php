    /**
     * A state file cannot blind the window either.
     *
     * observe() refuses a timestamp far in the future, because adopting one
     * makes prune() drop every bucket while observedSpan() still claims a full
     * window: the rules then read a complete basis holding nothing, which is
     * silence that looks like an answer. restore() took the clock straight out
     * of the state file, so the same blindness was reachable through the state
     * this module writes every cycle — and one NTP step forward is enough to
     * write it.
     */
    public function test_a_future_clock_in_restored_state_cannot_blind_the_window(): void
    {
        $window = new DnsResolutionWindow();
        $now = (float) time();

        $window->restore([
            'clock' => $now + 86400.0,
            'first_observed' => $now,
            'nxdomain' => [],
            'buckets' => [],
            'fired' => [],
        ]);

        $this->assertLessThanOrEqual($now + 600.0, $window->clock(), 'the restored clock is clamped, not adopted');
        $this->assertSame(1, $window->refusals()['future'], 'and the refusal is counted');

        // With the clock clamped the window can still take evidence, which is
        // the whole point: a blinded window accepts rows and retains none.
        $rules = new DnsAnomalyRules($window);
        $fired = [];

        foreach ($this->dgaLabels(14, 12, 5150) as $index => $label) {
            foreach ($rules->evaluate(
                $this->real(self::ANSWER_DOCKER_NXDOMAIN, $now + $index * 1.5, $label . '.restored-example.com')
            ) as $finding) {
                $fired[] = $finding['rule'];
            }
        }

        $this->assertSame(['DNS-001'], $fired, 'the window still holds what it observes');
    }

